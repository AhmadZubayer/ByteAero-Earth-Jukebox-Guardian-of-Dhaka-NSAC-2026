"""Sample a brightness transect from the Landsat 8 Dhaka frame (image/dhaka-landsat-2022.jpg).

Used by scene s05's "visual frame -> sound" demonstration. The values are mean
luma (0-255 sRGB) of the JPEG pixels along one horizontal band. They are NOT
temperature and not a calibrated Landsat product; the scene labels them that way.

Writes js/transect.js (window.EJ_TRANSECT) consumed by the chart and by timeline.js.
Requires ffmpeg on PATH (used only to decode the JPEG to raw grey pixels).
"""
import json
import pathlib
import subprocess

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "image" / "dhaka-landsat-2022.jpg"

# Crop shown in the s05 frame (source pixels). Must match css .s05-frame img positioning.
CROP = dict(x=450, y=250, w=1200, h=1200)
ROW_Y = 757          # transect row in source pixels (passes through central Dhaka)
BAND = 24            # band height in source pixels
NOTES = 38           # one note per 16th (0.15625 s) from 178.0 s to 183.8 s
TRACE = 120          # finer points for the drawn chart line

W, H = 1817, 1747
raw = subprocess.run(
    ["ffmpeg", "-v", "error", "-i", str(SRC), "-f", "rawvideo", "-pix_fmt", "gray", "-"],
    check=True, capture_output=True,
).stdout
img = np.frombuffer(raw, dtype=np.uint8).reshape(H, W).astype(float)

band = img[ROW_Y - BAND // 2: ROW_Y + BAND // 2, CROP["x"]: CROP["x"] + CROP["w"]]
col = band.mean(axis=0)


def bins(n):
    edges = np.linspace(0, len(col), n + 1).astype(int)
    return [round(float(col[a:b].mean()), 2) for a, b in zip(edges[:-1], edges[1:])]


out = {
    "source": "image/dhaka-landsat-2022.jpg (NASA Earth Observatory / USGS Landsat 8 OLI, 20 Mar 2022)",
    "measure": "mean JPEG luma 0-255 along a horizontal band; not temperature, not calibrated reflectance",
    "crop": CROP,
    "rowY": ROW_Y,
    "band": BAND,
    "notes": bins(NOTES),
    "trace": bins(TRACE),
}
js = (
    "/* Generated by tools/make_transect.py - do not edit by hand. */\n"
    "window.EJ_TRANSECT = " + json.dumps(out, indent=1) + ";\n"
)
(ROOT / "js" / "transect.js").write_text(js, encoding="utf-8")
print("notes min/max", min(out["notes"]), max(out["notes"]))
